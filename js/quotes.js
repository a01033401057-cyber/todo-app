// 주제별 아이콘
const QUOTE_ICONS = { 자존감: 'heart', 자신감: 'zap', 성장: 'sprout', 꾸준함: 'flame', 쉼: 'rest', 도전: 'flag', 미래: 'sparkles' };

// 날짜 → 그날의 문장 번호 (같은 날엔 늘 같고, 날마다 주제가 섞이도록 큰 소수만큼 건너뛴다)
function quoteIndex(dateText, shift = 0) {
  const [year, month, day] = dateText.split('-').map(Number);
  const dayNumber = Math.floor(Date.UTC(year, month - 1, day) / 86400000);
  const total = QUOTES.length;
  return (((dayNumber * 7919 + shift) % total) + total) % total;
}

// 그날 '다른 문장'을 누른 횟수 (그날만 기억)
function quoteShift(dateText) {
  const saved = store.ui.quote;
  return isPlainObject(saved) && saved.date === dateText ? Number(saved.shift) || 0 : 0;
}

function nextQuote(dateText) {
  store.ui.quote = { date: dateText, shift: quoteShift(dateText) + 1 };
  saveUi();
}

// 오늘의 한마디 카드
function quoteCard(dateText) {
  if (!store.settings.showQuote) return null;
  const [theme, text] = QUOTES[quoteIndex(dateText, quoteShift(dateText))];
  return h('section', { class: 'quote-card', 'aria-label': '오늘의 한마디' },
    h('span', { class: 'quote-mark', 'aria-hidden': 'true', text: '“' }),
    h('div', { class: 'quote-body' },
      h('span', { class: 'quote-eyebrow' }, icon(QUOTE_ICONS[theme] || 'sparkles', 14), `오늘의 한마디 · ${theme}`),
      h('p', { class: 'quote-text', text })),
    h('button', { type: 'button', class: 'icon-btn quote-next', 'aria-label': '다른 문장 보기', title: '다른 문장', data: actData('quote-next', { date: dateText }) }, icon('refresh', 16)));
}
